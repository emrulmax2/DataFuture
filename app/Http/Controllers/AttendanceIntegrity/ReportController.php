<?php

namespace App\Http\Controllers\AttendanceIntegrity;

use App\Exports\ArrayCollectionExport;
use App\Services\AttendanceIntegrity\Filters;
use App\Services\AttendanceIntegrity\IntegrityAccess;
use App\Services\AttendanceIntegrity\Lookup;
use App\Services\AttendanceIntegrity\ReportExporter;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Http\Request;
use Maatwebsite\Excel\Facades\Excel;

/**
 * Attendance Integrity > Reports: the ten reports (and every list's export) as
 * Excel, CSV or PDF. Needs Export. Every file carries the filters, when and by
 * whom it was made, and notes; every export is written to the access log.
 */
class ReportController extends IntegrityBaseController
{
    private const PDF_ROWS = 1500;

    public function index(Request $request)
    {
        IntegrityAccess::authorize('export');
        $f = Filters::fromRequest($request);
        IntegrityAccess::log('view', 'reports', null, $f->query());

        return $this->shell($request, 'pages.attendance-integrity.reports', 'Reports', [
            'filters' => $f,
            'reports' => ReportExporter::REPORTS,
        ]);
    }

    public function export(Request $request, string $report)
    {
        IntegrityAccess::authorize('export');
        abort_unless(isset(ReportExporter::REPORTS[$report]) || in_array($report, ['records', 'findings'], true), 404);
        $format = in_array($request->input('format'), ['xlsx', 'csv', 'pdf'], true) ? $request->input('format') : 'xlsx';
        @set_time_limit(300);

        $f = Filters::fromRequest($request);
        $built = ReportExporter::build($report, $f, ['metric' => $request->input('metric')]);
        IntegrityAccess::log('export', $report, null, ['format' => $format, 'rows' => count($built['rows'])] + $f->query());

        $header = [
            ['Report', $built['title']],
            ['Generated', now('Europe/London')->format('d/m/Y H:i').' (UK time)'],
            ['Generated by', Lookup::staffName(auth()->id())],
        ];
        foreach ($f->describe() as $label => $value) {
            $header[] = ['Filter: '.$label, $value];
        }
        foreach ($built['notes'] as $i => $note) {
            $header[] = [$i === 0 ? 'Notes' : '', $note];
        }
        $name = preg_replace('/[^A-Za-z0-9 \-]+/', '', $built['title']).' '.now('Europe/London')->format('Y-m-d Hi');

        if ($format === 'pdf') {
            $rows = array_slice($built['rows'], 0, self::PDF_ROWS);

            return Pdf::loadView('pages.attendance-integrity.pdf', [
                'title' => $built['title'],
                'header' => $header,
                'headings' => $built['headings'],
                'rows' => $rows,
                'truncated' => count($built['rows']) > self::PDF_ROWS ? count($built['rows']) : null,
            ])->setPaper('a4', count($built['headings']) > 7 ? 'landscape' : 'portrait')->download($name.'.pdf');
        }

        $sheet = array_merge($header, [[]], [$built['headings']], $built['rows']);
        if ($format === 'csv') {
            return response()->streamDownload(function () use ($sheet) {
                $out = fopen('php://output', 'w');
                fwrite($out, "\xEF\xBB\xBF"); // UTF-8 for Excel
                foreach ($sheet as $line) {
                    fputcsv($out, array_map(fn ($v) => is_bool($v) ? ($v ? 'Yes' : 'No') : $v, $line));
                }
                fclose($out);
            }, $name.'.csv', ['Content-Type' => 'text/csv; charset=UTF-8']);
        }

        return Excel::download(new ArrayCollectionExport($sheet, mb_substr(preg_replace('/[\\\\\/\?\*\[\]:]+/', ' ', $built['title']), 0, 31)), $name.'.xlsx');
    }
}
